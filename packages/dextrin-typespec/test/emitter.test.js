// Each fixture compiled by TypeSpec with this emitter: what it writes must
// mean what the fixture's expected .dxns says (decoded, compared in
// canonical form), and a second run must write the same bytes.

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readdir, readFile, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, NodeHost } from "@typespec/compiler";
import { decode, canonical, SchemaTree } from "@joetjen/dextrin";

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, "fixtures");
const emitter = join(here, "..");

/** Every file under `dir`, by its path relative to `dir`. */
async function files(dir, root = dir) {
  const out = {};
  for (const entry of await readdir(dir)) {
    const path = join(dir, entry);
    if ((await stat(path)).isDirectory()) Object.assign(out, await files(path, root));
    else out[relative(root, path)] = await readFile(path, "utf8");
  }
  return out;
}

/** Where the emitter wrote `fixture`'s files. */
async function emitted(fixture) {
  const outputDir = await mkdtemp(join(tmpdir(), "dextrin-typespec-"));
  const program = await compile(NodeHost, join(fixtures, fixture, "main.tsp"), {
    emit: [emitter],
    outputDir,
  });
  assert.deepEqual(
    program.diagnostics.map((d) => d.message),
    [],
    `TypeSpec reported problems for ${fixture}`,
  );
  return join(outputDir, "@joetjen/dextrin-typespec");
}

/** The emitter's output for `fixture`: its files by relative path. */
async function emit(fixture) {
  return files(await emitted(fixture));
}

/** What `text` means, as a string two equal documents share. */
function meaning(text) {
  return canonical(decode(text));
}

/** What the fixture expects: one namespace file, or a tree of them. */
async function expected(fixture) {
  const dir = join(fixtures, fixture);
  if ((await readdir(dir)).includes("expected.dxns")) {
    return { "Test.dxns": await readFile(join(dir, "expected.dxns"), "utf8") };
  }
  return files(join(dir, "expected"));
}

for (const fixture of (await readdir(fixtures)).filter((f) => !f.endsWith(".md"))) {
  test(`${fixture}: the emitter writes what the fixture expects`, async () => {
    const written = await emit(fixture);
    const wanted = await expected(fixture);
    assert.deepEqual(Object.keys(written).sort(), Object.keys(wanted).sort());
    for (const [path, text] of Object.entries(wanted)) {
      assert.equal(meaning(written[path]), meaning(text), `${fixture}: ${path}`);
    }
  });

  test(`${fixture}: what it writes is a schema tree dextrin check accepts`, async () => {
    const result = SchemaTree.load([await emitted(fixture)]);
    assert.deepEqual(result.ok ? [] : result.problems.map((p) => `${p.file}:${p.line}: ${p.message}`), []);
  });

  test(`${fixture}: a second run writes the same bytes`, async () => {
    assert.deepEqual(await emit(fixture), await emit(fixture));
  });
}

test("every file it writes says it is generated, and from where", async () => {
  for (const [path, text] of Object.entries(await emit("models"))) {
    assert.match(text, /^# Generated by @joetjen\/dextrin-typespec from .*main\.tsp; do not edit\./, path);
  }
});

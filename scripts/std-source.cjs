// Writes src/schema/std-source.cjs from priv/schema/std.dxns, the
// standard library's `.dxns` source (ported verbatim from `dextrin`'s).
//
// **Why the text is a module and not a file read at load**: a bundler --
// the DXN VS Code extension's esbuild -- puts the package in one file,
// and a path next to the source no longer leads anywhere. priv/ stays
// the source of truth; test/schema/std-source.spec.js fails when this
// has not been run after it changed.
//
//     npm run std
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'priv', 'schema', 'std.dxns'), 'utf8');
const out = `'use strict';

// Generated by scripts/std-source.cjs from priv/schema/std.dxns -- do not
// edit; edit that file and run \`npm run std\`.

/** The standard library's own \`.dxns\` source. */
module.exports = ${JSON.stringify(source)};
`;
fs.writeFileSync(path.join(root, 'src', 'schema', 'std-source.cjs'), out);
